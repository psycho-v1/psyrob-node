#!/usr/bin/env node
// Copy the init code and ABI of every system contract from the Foundry build (contracts/out) into
// genesis/artifacts.json, which the node uses to build the genesis state. Run after `forge build`:
//   cd contracts && forge build && cd .. && node genesis/export-artifacts.mjs
// The node never compiles anything; anyone can rebuild with the same solc (0.8.24, see contracts/foundry.toml) and
// compare this file.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const NAMES = ['GovernanceMode', 'Params', 'MinerRegistry', 'NGORegistry', 'Attestation', 'VoteEscrow', 'NGOElection', 'RoleElection',
  'Governor', 'Treasury', 'DevVesting', 'NGORewards', 'FinalityCommittee', 'FundApprovals', 'VolunteerFund', 'DevCouncil', 'UpgradeRegistry',
  'EmergencyPause'];
const out = { note: 'Generated by genesis/export-artifacts.mjs from contracts/out (solc 0.8.24, optimizer 200 runs, via-ir, shanghai).', contracts: {} };
for (const n of NAMES) {
  const file = path.join(ROOT, 'contracts/out', `${n}.sol`, `${n}.json`);
  const j = JSON.parse(fs.readFileSync(file, 'utf8'));
  const code = j.bytecode.object;
  out.contracts[n] = { initCode: code, initCodeSha256: createHash('sha256').update(code).digest('hex'), abi: j.abi };
}
fs.writeFileSync(path.join(ROOT, 'genesis/artifacts.json'), JSON.stringify(out, null, 1) + '\n');
console.log('wrote genesis/artifacts.json:', NAMES.length, 'contracts');
